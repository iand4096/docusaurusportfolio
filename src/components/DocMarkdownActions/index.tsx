import React, {useEffect, useRef, useState} from 'react';
import useDocusaurusContext from '@docusaurus/useDocusaurusContext';
import styles from './styles.module.css';

export default function DocMarkdownActions({permalink}: {permalink: string}): React.JSX.Element {
  const {siteConfig} = useDocusaurusContext();
  const baseUrl = siteConfig.baseUrl;
  const pagePath = permalink.replace(/\/$/, '');
  const markdownUrl = pagePath === baseUrl.replace(/\/$/, '')
    ? `${baseUrl}index.md`
    : `${pagePath}.md`;
  const [busy, setBusy] = useState(false);
  const [status, setStatus] = useState('');
  const [manualCopy, setManualCopy] = useState('');
  const request = useRef<AbortController | null>(null);
  const copyButton = useRef<HTMLButtonElement>(null);

  useEffect(() => () => request.current?.abort(), []);

  async function copyMarkdown() {
    setBusy(true);
    setStatus('');
    setManualCopy('');
    const controller = new AbortController();
    request.current = controller;
    try {
      const response = await fetch(markdownUrl, {signal: controller.signal});
      if (!response.ok || response.headers.get('content-type')?.includes('text/html')) {
        throw new Error('Markdown unavailable');
      }
      const markdown = await response.text();
      // Some static hosts return their HTML fallback with HTTP 200.
      if (!markdown.trim() || /^\s*(?:<!doctype html|<html\b)/i.test(markdown)) {
        throw new Error('Markdown unavailable');
      }
      if (controller.signal.aborted) return;
      try {
        if (!navigator.clipboard?.writeText) throw new Error('Clipboard unavailable');
        await navigator.clipboard.writeText(markdown);
        if (!controller.signal.aborted) setStatus('Markdown copied.');
      } catch {
        if (!controller.signal.aborted) {
          setManualCopy(markdown);
          setStatus('Automatic copying is unavailable. Select and copy the Markdown below.');
        }
      }
    } catch {
      if (!controller.signal.aborted) {
        setStatus(process.env.NODE_ENV === 'development'
          ? 'Markdown exports are generated by npm run build. Use npm run serve to preview them.'
          : 'The Markdown could not be loaded. Please try again.');
      }
    } finally {
      if (!controller.signal.aborted) setBusy(false);
    }
  }

  return (
    <div className={styles.actions}>
      <div className={styles.buttons} role="group" aria-label="Markdown page actions">
        <button ref={copyButton} type="button" className={styles.control}
          disabled={busy} onClick={copyMarkdown}>
          {busy ? 'Loading Markdown…' : 'Copy page as Markdown'}
        </button>
        <a className={styles.control} href={markdownUrl} target="_blank" rel="noopener noreferrer">
          View Markdown<span className={styles.srOnly}> (opens in a new tab)</span>
        </a>
      </div>
      <p className={styles.status} role="status" aria-live="polite">{status}</p>
      {manualCopy && <div className={styles.manualCopy}>
        <label>
          Markdown for this page
          <textarea readOnly rows={8} value={manualCopy} onFocus={event => event.target.select()} />
        </label>
        <button type="button" className={styles.control} onClick={() => {
          setManualCopy('');
          setStatus('');
          copyButton.current?.focus();
        }}>Close manual copy</button>
      </div>}
    </div>
  );
}
